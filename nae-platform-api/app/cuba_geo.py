def normalize_location(value: str | None) -> str:
    if not value:
        return ""
    import unicodedata
    normalized = unicodedata.normalize("NFD", str(value).strip())
    normalized = "".join(ch for ch in normalized if unicodedata.category(ch) != "Mn")
    return " ".join(normalized.lower().split())

def get_coordinates(provincia: str | None, municipio: str | None) -> dict[str, float] | None:
    provincia_norm = normalize_location(provincia)
    municipio_norm = normalize_location(municipio)
    for province_name, municipios in CUBA_GEO.items():
        if normalize_location(province_name) != provincia_norm:
            continue
        for item in municipios:
            if normalize_location(item["nombre"]) == municipio_norm:
                return {"lat": item["lat"], "lng": item["lng"]}
    return None